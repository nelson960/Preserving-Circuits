"""Exact geometry test for functional-manifold continual updates.

The experiment constructs a two-layer linear network with parameters ``U`` and
``V``.  Every stage supplies a new target factorization generated by an
invertible hidden-space transform ``S``::

    U_target = S U_0
    V_target = V_0 S^-1

Therefore ``V_target U_target == V_0 U_0`` exactly.  The desired internal
representation moves, but the protected input-output function does not.  This
lets us distinguish a fixed representation barrier from a true functional
constraint without relying on task labels or heuristic scores.
"""

