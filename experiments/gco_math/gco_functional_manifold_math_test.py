@dataclass(frozen=True)
class FactorShapes:
    input_dim: int
    hidden_dim: int
    output_dim: int

    @property
    def u_count(self) -> int:
        return self.hidden_dim * self.input_dim

    @property
    def parameter_count(self) -> int:
        return self.u_count + self.output_dim * self.hidden_dim


def unpack(theta: torch.Tensor, shapes: FactorShapes) -> tuple[torch.Tensor, torch.Tensor]:
    if theta.ndim != 1 or theta.numel() != shapes.parameter_count:
        raise ValueError("Flat factor vector has the wrong shape.")
    u = theta[: shapes.u_count].reshape(shapes.hidden_dim, shapes.input_dim)
    v = theta[shapes.u_count :].reshape(shapes.output_dim, shapes.hidden_dim)
    return u, v


def pack(u: torch.Tensor, v: torch.Tensor) -> torch.Tensor:
    return torch.cat([u.reshape(-1), v.reshape(-1)])


def hidden_states(theta: torch.Tensor, inputs: torch.Tensor, shapes: FactorShapes) -> torch.Tensor:
    u, _v = unpack(theta, shapes)
    return inputs @ u.T


def outputs(theta: torch.Tensor, inputs: torch.Tensor, shapes: FactorShapes) -> torch.Tensor:
    u, v = unpack(theta, shapes)
    return inputs @ u.T @ v.T


def protected_residual(
    theta: torch.Tensor,
    inputs: torch.Tensor,
    targets: torch.Tensor,
    shapes: FactorShapes,
) -> torch.Tensor:
    return (outputs(theta, inputs, shapes) - targets).reshape(-1)


def residual_jacobian(
    theta: torch.Tensor,
    inputs: torch.Tensor,
    targets: torch.Tensor,
    shapes: FactorShapes,
) -> tuple[torch.Tensor, torch.Tensor]:
    variable = theta.detach().requires_grad_(True)

    def residual_function(value: torch.Tensor) -> torch.Tensor:
        return protected_residual(value, inputs, targets, shapes)

    residual = residual_function(variable)
    jacobian = torch.autograd.functional.jacobian(
        residual_function,
        variable,
        vectorize=True,
    )
    if jacobian.shape != (residual.numel(), theta.numel()):
        raise RuntimeError("Protected Jacobian has an unexpected shape.")
    if not torch.isfinite(jacobian).all() or not torch.isfinite(residual).all():
        raise FloatingPointError("Protected residual or Jacobian is non-finite.")
    return residual.detach(), jacobian.detach()


def tangent_projection(
    gradient: torch.Tensor,
    jacobian: torch.Tensor,
    *,
    damping: float,
) -> tuple[torch.Tensor, dict[str, float]]:
    gram = jacobian @ jacobian.T
    identity = torch.eye(gram.shape[0], device=gram.device, dtype=gram.dtype)
    coefficients = torch.linalg.solve(
        gram + damping * identity,
        jacobian @ gradient,
    )
    tangent = gradient - jacobian.T @ coefficients
    raw_norm = torch.linalg.vector_norm(gradient).clamp_min(1e-12)
    tangent_norm = torch.linalg.vector_norm(tangent)
    singular = torch.linalg.svdvals(jacobian)
    rank = int((singular > singular[0].clamp_min(1e-12) * 1e-6).sum().item())
    return tangent, {
        "raw_norm": float(raw_norm.detach().cpu()),
        "tangent_norm": float(tangent_norm.detach().cpu()),
        "tangent_fraction": float((tangent_norm / raw_norm).detach().cpu()),
        "jacobian_rank": rank,
        "tangent_dimension": int(theta_width(jacobian) - rank),
    }


def theta_width(jacobian: torch.Tensor) -> int:
    if jacobian.ndim != 2:
        raise ValueError("Jacobian must be a matrix.")
    return int(jacobian.shape[1])


def normal_correction(
    theta: torch.Tensor,
    inputs: torch.Tensor,
    targets: torch.Tensor,
    shapes: FactorShapes,
    *,
    damping: float,
    iterations: int,
) -> tuple[torch.Tensor, float]:
    corrected = theta
    total_norm = 0.0
    for _iteration in range(iterations):
        residual, jacobian = residual_jacobian(corrected, inputs, targets, shapes)
        gram = jacobian @ jacobian.T
        identity = torch.eye(gram.shape[0], device=gram.device, dtype=gram.dtype)
        normal = -jacobian.T @ torch.linalg.solve(
            gram + damping * identity,
            residual,
        )
        corrected = corrected + normal
        total_norm += float(torch.linalg.vector_norm(normal).detach().cpu())
    return corrected.detach(), total_norm


def linear_cka(left: torch.Tensor, right: torch.Tensor) -> float:
    if left.shape != right.shape or left.ndim != 2:
        raise ValueError("CKA inputs must be equally shaped matrices.")
    left = left - left.mean(dim=0, keepdim=True)
    right = right - right.mean(dim=0, keepdim=True)
    numerator = (left.T @ right).square().sum()
    denominator = torch.sqrt(
        (left.T @ left).square().sum() * (right.T @ right).square().sum()
    ).clamp_min(1e-12)
    return float((numerator / denominator).detach().cpu())


def target_factors(
    base_u: torch.Tensor,
    base_v: torch.Tensor,
    *,
    stage: int,
    stages: int,
    log_condition: float,
) -> tuple[torch.Tensor, torch.Tensor]:
    progress = stage / stages
    coordinates = torch.linspace(
        -1.0,
        1.0,
        base_u.shape[0],
        device=base_u.device,
        dtype=base_u.dtype,
    )
    scale = torch.exp(progress * log_condition * coordinates)
    transform = torch.diag(scale)
    inverse = torch.diag(scale.reciprocal())
    return transform @ base_u, base_v @ inverse


def factor_objective(
    theta: torch.Tensor,
    target_u: torch.Tensor,
    target_v: torch.Tensor,
    shapes: FactorShapes,
) -> torch.Tensor:
    u, v = unpack(theta, shapes)
    return 0.5 * ((u - target_u).square().mean() + (v - target_v).square().mean())


def clipped_step(direction: torch.Tensor, *, learning_rate: float, trust_radius: float) -> torch.Tensor:
    delta = -learning_rate * direction
    norm = torch.linalg.vector_norm(delta)
    scale = torch.clamp(delta.new_tensor(trust_radius) / norm.clamp_min(1e-12), max=1.0)
    return delta * scale


def train_method(
    *,
    method: str,
    initial_theta: torch.Tensor,
    base_u: torch.Tensor,
    base_v: torch.Tensor,
    inputs: torch.Tensor,
    protected_targets: torch.Tensor,
    shapes: FactorShapes,
    args: argparse.Namespace,
) -> dict[str, Any]:
    theta = initial_theta.clone()
    initial_hidden = hidden_states(theta, inputs, shapes).detach()
    rows: list[dict[str, Any]] = []
    accepted = 0
    for stage in range(1, args.stages + 1):
        target_stage = stage if args.target_schedule == "ramp" else args.stages
        target_u, target_v = target_factors(
            base_u,
            base_v,
            stage=target_stage,
            stages=args.stages,
            log_condition=args.log_condition,
        )
        before = float(factor_objective(theta, target_u, target_v, shapes).detach().cpu())
        candidate = theta.detach().requires_grad_(True)
        objective = factor_objective(candidate, target_u, target_v, shapes)
        gradient = torch.autograd.grad(objective, candidate)[0].detach()
        _residual, jacobian = residual_jacobian(
            theta,
            inputs,
            protected_targets,
            shapes,
        )
        tangent, tangent_report = tangent_projection(
            gradient,
            jacobian,
            damping=args.damping,
        )
        full_delta = clipped_step(
            tangent,
            learning_rate=args.learning_rate,
            trust_radius=args.trust_radius,
        )
        trial: torch.Tensor | None = None
        normal_norm = 0.0
        after = before
        output_error = math.inf
        fixed_cka = linear_cka(hidden_states(theta, inputs, shapes), initial_hidden)
        accepted_scale = 0.0
        for attempt in range(args.backtracking_steps + 1):
            scale = args.backtracking_factor**attempt
            proposed, proposed_normal_norm = normal_correction(
                theta + scale * full_delta,
                inputs,
                protected_targets,
                shapes,
                damping=args.damping,
                iterations=args.normal_iterations,
            )
            proposed_cka = linear_cka(hidden_states(proposed, inputs, shapes), initial_hidden)
            proposed_after = float(
                factor_objective(proposed, target_u, target_v, shapes).detach().cpu()
            )
            proposed_error = float(
                protected_residual(proposed, inputs, protected_targets, shapes)
                .square()
                .mean()
                .detach()
                .cpu()
            )
            cka_passed = method == "functional_manifold" or proposed_cka >= args.cka_floor
            if cka_passed and proposed_after < before and proposed_error <= args.protected_tolerance:
                trial = proposed
                normal_norm = proposed_normal_norm
                after = proposed_after
                output_error = proposed_error
                fixed_cka = proposed_cka
                accepted_scale = scale
                break
        stage_accepted = trial is not None
        if stage_accepted:
            if trial is None:
                raise RuntimeError("Accepted stage has no trial parameters.")
            theta = trial
            accepted += 1
        current_hidden = hidden_states(theta, inputs, shapes)
        rows.append(
            {
                "stage": stage,
                "accepted": stage_accepted,
                "target_loss_before": before,
                "target_loss_after": (
                    after if stage_accepted else before
                ),
                "protected_mse": float(
                    protected_residual(theta, inputs, protected_targets, shapes)
                    .square()
                    .mean()
                    .detach()
                    .cpu()
                ),
                "fixed_cka": linear_cka(current_hidden, initial_hidden),
                "normal_norm": normal_norm,
                "accepted_scale": accepted_scale,
                **tangent_report,
            }
        )
    return {
        "method": method,
        "accepted": accepted,
        "stages": rows,
        "final_target_loss": rows[-1]["target_loss_after"],
        "final_protected_mse": rows[-1]["protected_mse"],
        "final_fixed_cka": rows[-1]["fixed_cka"],
        "minimum_fixed_cka": min(row["fixed_cka"] for row in rows),
        "minimum_tangent_dimension": min(row["tangent_dimension"] for row in rows),
    }


def plot_results(results: dict[str, dict[str, Any]], output_path: Path) -> None:
    fig, axes = plt.subplots(2, 2, figsize=(11.5, 8.0))
    colors = {"fixed_cka": "#dc2626", "functional_manifold": "#2563eb"}
    for method, result in results.items():
        stages = result["stages"]
        x = [row["stage"] for row in stages]
        color = colors[method]
        axes[0, 0].plot(x, [row["target_loss_after"] for row in stages], color=color, label=method)
        axes[0, 1].plot(x, [row["fixed_cka"] for row in stages], color=color, label=method)
        axes[1, 0].plot(x, [row["protected_mse"] for row in stages], color=color, label=method)
        axes[1, 1].plot(x, [row["tangent_fraction"] for row in stages], color=color, label=method)
    axes[0, 0].set_title("New factorization objective")
    axes[0, 0].set_yscale("log")
    axes[0, 1].set_title("Similarity to original hidden geometry")
    axes[0, 1].axhline(results["fixed_cka"]["config"]["cka_floor"], color="#111827", linestyle="--")
    axes[1, 0].set_title("Protected function residual")
    axes[1, 0].set_yscale("log")
    axes[1, 1].set_title("Usable tangent gradient")
    for axis in axes.flat:
        axis.set_xlabel("stage")
        axis.grid(alpha=0.25)
        axis.legend()
    fig.tight_layout()
    fig.savefig(output_path, dpi=180)
    plt.close(fig)


def validate_args(args: argparse.Namespace) -> None:
    for name in (
        "input_dim",
        "hidden_dim",
        "output_dim",
        "anchors",
        "stages",
        "normal_iterations",
        "backtracking_steps",
    ):
        if getattr(args, name) <= 0:
            raise ValueError(f"--{name.replace('_', '-')} must be positive.")
    if args.hidden_dim < 2:
        raise ValueError("--hidden-dim must be at least 2.")
    for name in ("learning_rate", "trust_radius", "damping", "protected_tolerance", "log_condition"):
        value = getattr(args, name)
        if value <= 0.0 or not math.isfinite(value):
            raise ValueError(f"--{name.replace('_', '-')} must be positive and finite.")
    if not 0.0 < args.cka_floor < 1.0:
        raise ValueError("--cka-floor must be in (0, 1).")
    if not 0.0 < args.backtracking_factor < 1.0:
        raise ValueError("--backtracking-factor must be in (0, 1).")


def run(args: argparse.Namespace) -> None:
    validate_args(args)
    random.seed(args.seed)
    torch.manual_seed(args.seed)
    device = resolve_device(args.device)
    shapes = FactorShapes(args.input_dim, args.hidden_dim, args.output_dim)
    dtype = torch.float64
    inputs = torch.randn(args.anchors, args.input_dim, device=device, dtype=dtype)
    base_u = torch.randn(
        args.hidden_dim, args.input_dim, device=device, dtype=dtype
    ) / math.sqrt(args.input_dim)
    base_v = torch.randn(
        args.output_dim, args.hidden_dim, device=device, dtype=dtype
    ) / math.sqrt(args.hidden_dim)
    initial_theta = pack(base_u, base_v).detach()
    protected_targets = outputs(initial_theta, inputs, shapes).detach()
    results: dict[str, dict[str, Any]] = {}
    for method in ("fixed_cka", "functional_manifold"):
        result = train_method(
            method=method,
            initial_theta=initial_theta,
            base_u=base_u,
            base_v=base_v,
            inputs=inputs,
            protected_targets=protected_targets,
            shapes=shapes,
            args=args,
        )
        result["config"] = {
            key: str(value) if isinstance(value, Path) else value
            for key, value in vars(args).items()
        }
        results[method] = result

    args.output_dir.mkdir(parents=True, exist_ok=True)
    output_json = args.output_dir / "functional_manifold_math.json"
    output_plot = args.output_dir / "functional_manifold_math.png"
    plot_results(results, output_plot)
    output_json.write_text(json.dumps(results, indent=2), encoding="utf-8")
    print("FUNCTIONAL MANIFOLD MATH TEST")
    print("=" * 112)
    for method, result in results.items():
        print(
            f"{method:>22} accepted={result['accepted']:4d}/{args.stages} "
            f"target={result['final_target_loss']:.6g} "
            f"protected={result['final_protected_mse']:.3g} "
            f"fixedCKA={result['final_fixed_cka']:.4f} "
            f"tangentDim>={result['minimum_tangent_dimension']}"
        )
    print(f"wrote_json={output_json}")
    print(f"wrote_plot={output_plot}")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--device", choices=("cpu", "cuda", "mps"), default="cpu")
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--input-dim", type=int, default=6)
    parser.add_argument("--hidden-dim", type=int, default=8)
    parser.add_argument("--output-dim", type=int, default=3)
    parser.add_argument("--anchors", type=int, default=4)
    parser.add_argument("--stages", type=int, default=500)
    parser.add_argument("--learning-rate", type=float, default=1.0)
    parser.add_argument("--trust-radius", type=float, default=0.2)
    parser.add_argument("--damping", type=float, default=1e-5)
    parser.add_argument("--normal-iterations", type=int, default=2)
    parser.add_argument("--backtracking-steps", type=int, default=12)
    parser.add_argument("--backtracking-factor", type=float, default=0.5)
    parser.add_argument("--protected-tolerance", type=float, default=1e-7)
    parser.add_argument("--cka-floor", type=float, default=0.95)
    parser.add_argument("--log-condition", type=float, default=4.0)
    parser.add_argument(
        "--target-schedule",
        choices=("final", "ramp"),
        default="final",
        help="Use one fixed equivalent factorization or move it gradually across stages.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("model/analysis/gco-functional-manifold-math-seed0"),
    )
    return parser


def main() -> None:
    run(build_parser().parse_args())


if __name__ == "__main__":
    main()
